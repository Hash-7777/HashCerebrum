// Builds a Markdown peer-review report from a completed PaperReview — the same
// content as reviewReportPdf, in a portable text format reviewers can paste
// into email, GitHub, or a doc. Pure: no DOM or platform access.

import type { ReviewedPaper } from '@core/store/peerReviewStore';
import { REVIEW_SWARM_AGENTS } from './reviewSwarm';

export function buildReviewReportMarkdown(paper: ReviewedPaper): string {
  const { review } = paper;
  if (!review) throw new Error('No review available to export.');

  const date = new Date(review.reviewedAt).toLocaleDateString('en-GB', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  });

  const out: string[] = [];
  out.push('# Peer Review Report');
  out.push('');
  out.push(`## ${paper.title}`);
  out.push('');
  out.push(`**Score:** ${review.score}/10  `);
  out.push(`**Reviewed:** ${date}  `);
  out.push(`**Model:** ${review.modelUsed}`);
  out.push('');
  out.push('---');
  out.push('');
  out.push('## Overall Assessment');
  out.push('');
  out.push(review.summary.trim());
  out.push('');

  if (review.strengths.length > 0) {
    out.push('### Strengths');
    out.push('');
    for (const s of review.strengths) out.push(`- ${s.trim()}`);
    out.push('');
  }
  if (review.weaknesses.length > 0) {
    out.push('### Weaknesses');
    out.push('');
    for (const w of review.weaknesses) out.push(`- ${w.trim()}`);
    out.push('');
  }

  const standard: [string, string][] = [
    ['Methodology', review.methodology],
    ['Statistics', review.statistics],
    ['Conclusions', review.conclusions],
    ['Publication Readiness', review.publishReadiness],
  ];
  for (const [title, text] of standard) {
    if (!text || !text.trim()) continue;
    out.push(`## ${title}`);
    out.push('');
    out.push(text.trim());
    out.push('');
  }

  const agentResults = review.agentResults ?? [];
  const doneAgents = REVIEW_SWARM_AGENTS.filter((a) => a.agentId !== 'orchestrator')
    .map((def) => ({ def, result: agentResults.find((r) => r.agentId === def.agentId) }))
    .filter((x) => x.result && x.result.status === 'done' && x.result.text.trim());

  if (doneAgents.length > 0) {
    out.push('## Swarm Agent Analysis');
    out.push('');
    for (const { def, result } of doneAgents) {
      out.push(`### ${def.label}`);
      out.push('');
      if (result!.items.length > 0) {
        for (const item of result!.items) out.push(`- ${item.trim()}`);
      } else {
        out.push(result!.text.trim());
      }
      out.push('');
    }
  }

  out.push('---');
  out.push('');
  out.push(`*Generated by HashCerebrum Peer Review · ${date}*`);
  out.push('');

  return out.join('\n');
}
