// Full, must-acknowledge safety disclaimer for the Drug-Interactions checker.
// Drug-interaction calls are critical clinical decisions, so the first time the
// mode is opened this gates use behind an explicit acknowledgement; it can be
// re-opened any time from the panel. Portaled to <body> with a high z-index so
// it sits above all app chrome.

import { createPortal } from 'react-dom';
import { Icon } from '@ui/icons';

// v2: the v1 gate could fire on app launch (the mode mounts hidden) and may
// already have been acknowledged there; bumping the key makes it appear fresh
// on the first real entry into Drug-Interactions mode.
const ACK_KEY = 'hc.drugInteractions.disclaimerAck.v2';

export function hasAckedDiDisclaimer(): boolean {
  try {
    return localStorage.getItem(ACK_KEY) === '1';
  } catch {
    return false;
  }
}

function ackDiDisclaimer(): void {
  try {
    localStorage.setItem(ACK_KEY, '1');
  } catch {
    /* private mode / storage disabled — the gate simply shows again next time. */
  }
}

const POINTS: Array<{ heading: string; body: string }> = [
  {
    heading: 'For information only — not a medical device',
    body: 'This checker is an automated, educational triage aid. It has no FDA, EMA, or other regulatory approval and is not intended to diagnose, treat, prescribe, dispense, or prevent any condition. It is not for use by anyone under 18.',
  },
  {
    heading: 'It can be wrong or incomplete',
    body: 'Grades are generated by AI from drug-label and published-literature sources that may be outdated, incomplete, or misinterpreted. A grade of “None” does not prove an interaction is absent, and a serious grade is not a confirmed diagnosis. Doses, foods, herbs, comorbidities, and patient-specific factors are not fully accounted for.',
  },
  {
    heading: 'Always confirm with a professional',
    body: 'Never make a prescribing, dispensing, or combination decision from this output alone. Always verify every result with a licensed pharmacist or physician who can assess the individual patient before any clinical action is taken.',
  },
  {
    heading: 'No warranty, no liability',
    body: 'The software is provided “as is”, without warranty of any kind. To the fullest extent permitted by law, the authors accept no liability for any harm, loss, wrong result, or decision arising from its use. You are responsible for how you use it.',
  },
];

export function DrugInteractionDisclaimer({
  mode,
  onClose,
}: {
  /** 'gate' = first-run acknowledgement required; 'review' = re-opened, dismissible. */
  mode: 'gate' | 'review';
  onClose: () => void;
}) {
  const accept = () => {
    ackDiDisclaimer();
    onClose();
  };

  return createPortal(
    <div
      className="di-disc-layer"
      onPointerDown={(event) => {
        // Only the re-opened view dismisses on backdrop click; the first-run
        // gate must be explicitly acknowledged.
        if (mode === 'review' && event.target === event.currentTarget) onClose();
      }}
    >
      <section className="di-disc-modal" onPointerDown={(event) => event.stopPropagation()} aria-label="Drug interaction safety disclaimer">
        <header className="di-disc-head">
          <Icon name="alert" size={18} />
          <h2>Before you use the interaction checker</h2>
        </header>
        <div className="di-disc-body">
          <p className="di-disc-lead">
            Drug-interaction decisions are critical. Please read and accept the following before continuing.
          </p>
          {POINTS.map((point) => (
            <div key={point.heading} className="di-disc-point">
              <strong>{point.heading}</strong>
              <p>{point.body}</p>
            </div>
          ))}
          <p className="di-disc-accept-line">
            By continuing you confirm you understand these terms and that this tool does not replace
            professional medical judgement.
          </p>
        </div>
        <footer className="di-disc-foot">
          {mode === 'gate' ? (
            <button type="button" className="di-disc-accept" onClick={accept}>
              I understand and agree
            </button>
          ) : (
            <button type="button" className="di-disc-dismiss" onClick={onClose}>
              Close
            </button>
          )}
        </footer>
      </section>
    </div>,
    globalThis.document.body,
  );
}
