// Protocol mode — structured study design and PICO-driven protocol drafting.
// Helps researchers outline a study before data collection, with exportable
// protocol documents suitable for ethics review or registry pre-registration.

import { useState } from 'react';
import { useProjectStore } from '@core/store/projectStore';
import { Icon } from '@ui/icons';
import { useReviewStorage } from '@features/review/useReviewStorage';

type StudyDesign =
  | 'rct'
  | 'cohort'
  | 'case_control'
  | 'cross_sectional'
  | 'diagnostic_accuracy'
  | 'systematic_review';

const DESIGNS: { value: StudyDesign; label: string }[] = [
  { value: 'rct', label: 'Randomised controlled trial' },
  { value: 'cohort', label: 'Cohort study' },
  { value: 'case_control', label: 'Case–control study' },
  { value: 'cross_sectional', label: 'Cross-sectional study' },
  { value: 'diagnostic_accuracy', label: 'Diagnostic accuracy study' },
  { value: 'systematic_review', label: 'Systematic review' },
];

function designLabel(d: StudyDesign): string {
  return DESIGNS.find((x) => x.value === d)?.label ?? d;
}

function generateOutline(fields: {
  title: string;
  design: StudyDesign;
  population: string;
  intervention: string;
  comparator: string;
  outcome: string;
  eligibility: string;
  primaryEndpoint: string;
  secondaryEndpoints: string;
  sampleSize: string;
  duration: string;
  analysisPlan: string;
}): string {
  const lines: string[] = [];
  lines.push(`# ${fields.title || 'Study Protocol'}`);
  lines.push('');
  lines.push(`**Design:** ${designLabel(fields.design)}`);
  lines.push('');
  lines.push('## Background and rationale');
  lines.push('(To be completed by the researcher)');
  lines.push('');
  lines.push('## Objectives');
  lines.push('');
  lines.push('### Primary objective');
  lines.push(fields.primaryEndpoint || '(Not specified)');
  lines.push('');
  if (fields.secondaryEndpoints.trim()) {
    lines.push('### Secondary objectives');
    for (const line of fields.secondaryEndpoints.split('\n').filter(Boolean)) {
      lines.push(`- ${line}`);
    }
    lines.push('');
  }
  lines.push('## Study design');
  lines.push(`This is a ${designLabel(fields.design).toLowerCase()}.`);
  lines.push('');
  lines.push('## Population');
  lines.push(fields.population || '(Not specified)');
  lines.push('');
  if (fields.eligibility.trim()) {
    lines.push('### Eligibility criteria');
    for (const line of fields.eligibility.split('\n').filter(Boolean)) {
      lines.push(`- ${line}`);
    }
    lines.push('');
  }
  if (fields.design === 'rct' || fields.design === 'cohort' || fields.design === 'case_control') {
    lines.push('## Intervention / Exposure');
    lines.push(fields.intervention || '(Not specified)');
    lines.push('');
    if (fields.design === 'rct') {
      lines.push('## Comparator');
      lines.push(fields.comparator || '(Not specified)');
      lines.push('');
    }
  }
  lines.push('## Outcome measures');
  lines.push(fields.outcome || '(Not specified)');
  lines.push('');
  if (fields.sampleSize.trim()) {
    lines.push('## Sample size');
    lines.push(fields.sampleSize);
    lines.push('');
  }
  if (fields.duration.trim()) {
    lines.push('## Duration and timeline');
    lines.push(fields.duration);
    lines.push('');
  }
  if (fields.analysisPlan.trim()) {
    lines.push('## Statistical analysis plan');
    lines.push(fields.analysisPlan);
    lines.push('');
  }
  lines.push('## Ethics and declarations');
  lines.push('- Institutional review board approval: (pending / reference)');
  lines.push('- Informed consent: (required / waived)');
  lines.push('- Trial registration: (e.g. ClinicalTrials.gov ID)');
  lines.push('- Funding and conflicts of interest: (to be declared)');
  lines.push('');
  lines.push('---');
  lines.push('*Generated by HashCerebrum Protocol mode*');
  return lines.join('\n');
}

export function ProtocolMode() {
  const activeProjectId = useProjectStore((s) => s.activeProjectId);
  const { assessments, save, remove } = useReviewStorage(activeProjectId, 'protocol');
  const [title, setTitle] = useState('');
  const [design, setDesign] = useState<StudyDesign>('rct');
  const [population, setPopulation] = useState('');
  const [intervention, setIntervention] = useState('');
  const [comparator, setComparator] = useState('');
  const [outcome, setOutcome] = useState('');
  const [eligibility, setEligibility] = useState('');
  const [primaryEndpoint, setPrimaryEndpoint] = useState('');
  const [secondaryEndpoints, setSecondaryEndpoints] = useState('');
  const [sampleSize, setSampleSize] = useState('');
  const [duration, setDuration] = useState('');
  const [analysisPlan, setAnalysisPlan] = useState('');

  const outline = generateOutline({
    title,
    design,
    population,
    intervention,
    comparator,
    outcome,
    eligibility,
    primaryEndpoint,
    secondaryEndpoints,
    sampleSize,
    duration,
    analysisPlan,
  });

  const copyOutline = async () => {
    try {
      await navigator.clipboard.writeText(outline);
    } catch {
      const textarea = document.createElement('textarea');
      textarea.value = outline;
      document.body.appendChild(textarea);
      textarea.select();
      document.execCommand('copy');
      document.body.removeChild(textarea);
    }
  };

  const usesPico = design === 'rct' || design === 'cohort' || design === 'case_control';
  const usesComparator = design === 'rct';

  return (
    <div className="mode protocol-mode">
      <section className="protocol-main" aria-label="Study protocol">
        <header className="protocol-toolbar">
          <div>
            <p className="eyebrow">
              <Icon name="flask" size={10} /> Protocol
            </p>
            <h1>Study design</h1>
            <p className="protocol-subtitle">PICO-driven protocol drafting for ethics and registry pre-registration</p>
          </div>
          <div className="protocol-tools">
            <button type="button" className="protocol-export" onClick={() => void copyOutline()}>
              <Icon name="copy" size={12} /> Copy Markdown
            </button>
            <button
              type="button"
              className="protocol-export"
              onClick={() =>
                save('protocol', title || '(untitled protocol)', {
                  title,
                  design,
                  population,
                  intervention,
                  comparator,
                  outcome,
                  eligibility,
                  primaryEndpoint,
                  secondaryEndpoints,
                  sampleSize,
                  duration,
                  analysisPlan,
                })
              }
            >
              <Icon name="document" size={12} /> Save
            </button>
          </div>
        </header>

        <div className="protocol-form">
          <label className="protocol-field protocol-field-wide">
            <span>Study title</span>
            <input
              type="text"
              placeholder="e.g. Effect of X on Y in Z population"
              value={title}
              onChange={(e) => setTitle(e.target.value)}
              maxLength={200}
            />
          </label>

          <label className="protocol-field">
            <span>Study design</span>
            <select value={design} onChange={(e) => setDesign(e.target.value as StudyDesign)}>
              {DESIGNS.map((d) => (
                <option key={d.value} value={d.value}>
                  {d.label}
                </option>
              ))}
            </select>
          </label>

          <label className="protocol-field protocol-field-wide">
            <span>Population</span>
            <input
              type="text"
              placeholder="Who will be studied?"
              value={population}
              onChange={(e) => setPopulation(e.target.value)}
            />
          </label>

          {usesPico && (
            <label className="protocol-field protocol-field-wide">
              <span>Intervention / Exposure</span>
              <input
                type="text"
                placeholder="What is being tested or measured?"
                value={intervention}
                onChange={(e) => setIntervention(e.target.value)}
              />
            </label>
          )}

          {usesComparator && (
            <label className="protocol-field protocol-field-wide">
              <span>Comparator</span>
              <input
                type="text"
                placeholder="Control arm or alternative intervention"
                value={comparator}
                onChange={(e) => setComparator(e.target.value)}
              />
            </label>
          )}

          <label className="protocol-field protocol-field-wide">
            <span>Outcome</span>
            <input
              type="text"
              placeholder="Primary outcome measure"
              value={outcome}
              onChange={(e) => setOutcome(e.target.value)}
            />
          </label>

          <label className="protocol-field protocol-field-wide">
            <span>Eligibility criteria</span>
            <textarea
              placeholder="One criterion per line…"
              value={eligibility}
              onChange={(e) => setEligibility(e.target.value)}
              rows={4}
            />
          </label>

          <label className="protocol-field protocol-field-wide">
            <span>Primary endpoint</span>
            <input
              type="text"
              placeholder="The single main outcome the study is powered to detect"
              value={primaryEndpoint}
              onChange={(e) => setPrimaryEndpoint(e.target.value)}
            />
          </label>

          <label className="protocol-field protocol-field-wide">
            <span>Secondary endpoints</span>
            <textarea
              placeholder="One endpoint per line…"
              value={secondaryEndpoints}
              onChange={(e) => setSecondaryEndpoints(e.target.value)}
              rows={3}
            />
          </label>

          <label className="protocol-field">
            <span>Target sample size</span>
            <input
              type="text"
              placeholder="e.g. 240 (120 per arm)"
              value={sampleSize}
              onChange={(e) => setSampleSize(e.target.value)}
            />
          </label>

          <label className="protocol-field">
            <span>Duration</span>
            <input
              type="text"
              placeholder="e.g. 12 months"
              value={duration}
              onChange={(e) => setDuration(e.target.value)}
            />
          </label>

          <label className="protocol-field protocol-field-wide">
            <span>Analysis plan</span>
            <textarea
              placeholder="Planned statistical tests, handling of missing data, subgroup analyses…"
              value={analysisPlan}
              onChange={(e) => setAnalysisPlan(e.target.value)}
              rows={4}
            />
          </label>
        </div>

        <div className="protocol-preview">
          <h3>Protocol outline</h3>
          <pre>{outline}</pre>
        </div>

        {assessments.length > 0 && (
          <div className="review-saved">
            <h3>Saved protocols</h3>
            <ul>
              {assessments.map((a) => (
                <li key={a.id}>
                  <span className="review-saved-meta">
                    <strong>{a.studyTitle}</strong>
                    <span>{new Date(a.createdAt).toLocaleDateString()}</span>
                  </span>
                  <button
                    type="button"
                    className="review-saved-delete"
                    onClick={() => remove(a.id)}
                    aria-label={`Delete ${a.studyTitle}`}
                  >
                    <Icon name="close" size={11} />
                  </button>
                </li>
              ))}
            </ul>
          </div>
        )}
      </section>
    </div>
  );
}
